import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import { ART_STAND_INS, SHIP_MODELS } from "./ship-model-catalog.mjs";

const client = fileURLToPath(new URL("..", import.meta.url));
const source = path.join(client, "art-src/ship-models/interceptor-lod-experiment-v1/models");
const destination = path.join(client, "public/art/derived/ship-models/v1");
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
async function writeChanged(file, data) {
  if (hash(await readFile(file).catch(() => Buffer.alloc(0))) === hash(data)) return 0;
  await writeFile(file, data);
  return 1;
}

export async function buildShipModelAssets() {
  await mkdir(destination, { recursive: true });
  const catalog = {}, manifest = { recipe: "approved-lod2-byte-identical-v1", ships: {} };
  let written = 0;
  for (const { kind, id, title } of SHIP_MODELS) {
    const file = `${id}-lod2.glb`, input = path.join(source, file);
    const bytes = await readFile(input);
    const gltf = JSON.parse(bytes.subarray(20, 20 + bytes.readUInt32LE(12)).toString());
    const triangles = gltf.meshes.reduce((n, mesh) => n + mesh.primitives.reduce((m, p) => m + gltf.accessors[p.indices].count / 3, 0), 0);
    const sha256 = hash(bytes);
    written += await writeChanged(path.join(destination, file), bytes);
    catalog[kind] = { id, title, triangles, url: `/art/derived/ship-models/v1/${file}?v=${sha256.slice(0, 12)}`,
      poster: `/art/derived/ships/models-v1/previews/${kind}-768.webp` };
    manifest.ships[kind] = { ...catalog[kind], bytes: bytes.length, sha256, source: path.relative(client, input) };
  }
  for (const [kind, { from, title }] of Object.entries(ART_STAND_INS)) catalog[kind] = { ...catalog[from], title };
  await writeChanged(path.join(destination, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  await writeChanged(path.join(client, "src/ship-models.generated.ts"),
    '// Generated by scripts/build-ship-model-assets.mjs. Only the approved lowest-detail meshes ship.\n' +
    'import type { ShipKind } from "./protocol";\n' +
    `export const SHIP_MODELS = ${JSON.stringify(catalog, null, 2)} as const satisfies Record<ShipKind, { id: string; title: string; triangles: number; url: string; poster: string }>;\n`);
  return { sources: SHIP_MODELS.length, written };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  console.log("Ship models:", await buildShipModelAssets());
}
