import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import sharp from "sharp";

export const PLANET_ART_VERSION = "2026-09-08";
export const PLANET_ART_SIZES = [32, 64, 128, 256, 512, 1024, 1254];
export const PLANET_ART_KINDS = ["terrestrial", "desert", "ocean", "ice", "gas_giant", "lava", "barren", "moon"];
const clientRoot = fileURLToPath(new URL("..", import.meta.url));
const recipe = "full-canvas-mitchell-rgba-v1";
const hash = bytes => createHash("sha256").update(bytes).digest("hex");
const readJson = async file => JSON.parse(await readFile(file, "utf8"));
async function writeChanged(file, text) {
  if (await readFile(file, "utf8").catch(() => null) !== text) await writeFile(file, text);
}

async function geometry(bytes) {
  const { data, info } = await sharp(bytes).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width, right = -1, top = info.height, bottom = -1, clear = 0;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
    const alpha = data[(y * info.width + x) * 4 + 3];
    if (alpha === 0) clear++;
    // Measure the disk, not a faint atmospheric fringe. One master geometry
    // serves every mip level, so changing source size cannot move/grow a body.
    if (alpha < 128) continue;
    left = Math.min(left, x); right = Math.max(right, x);
    top = Math.min(top, y); bottom = Math.max(bottom, y);
  }
  assert.ok(clear > info.width * info.height * .15, "real transparency required, not a painted checkerboard");
  assert.ok(right > left && bottom > top);
  return {
    anchor: [(left + right + 1) / (2 * info.width), (top + bottom + 1) / (2 * info.height)],
    visualRatio: Math.max(right - left + 1, bottom - top + 1) / info.width,
  };
}

export async function buildPlanetDerivatives() {
  const inputRoot = path.join(clientRoot, "art-src", `planets-${PLANET_ART_VERSION}`);
  const outputRoot = path.join(clientRoot, "public", "art", "derived", "planets", PLANET_ART_VERSION);
  await mkdir(outputRoot, { recursive: true });
  const manifestFile = path.join(outputRoot, "manifest.json");
  const previous = await readJson(manifestFile).catch(() => null);
  const manifest = { version: PLANET_ART_VERSION, recipe, sizes: PLANET_ART_SIZES, planets: [] };
  let written = 0;
  for (const slug of PLANET_ART_KINDS) {
    const source = path.join(inputRoot, `${slug}.png`);
    const bytes = await readFile(source);
    const sourceSha256 = hash(bytes);
    const meta = await sharp(bytes).metadata();
    assert.equal(meta.width, 1254, `${slug}: keep the original native master`);
    assert.equal(meta.height, 1254);
    assert.ok(meta.hasAlpha, `${slug}: RGBA source required`);
    const measured = await geometry(bytes);
    const old = previous?.recipe === recipe
      ? previous.planets.find(p => p.slug === slug && p.sourceSha256 === sourceSha256) : null;
    const levels = [];
    for (const size of PLANET_ART_SIZES) {
      const file = `${slug}-${size}.png`;
      const output = path.join(outputRoot, file);
      const cached = old?.levels.find(level => level.size === size);
      if (cached && await stat(output).then(s => s.size === cached.bytes).catch(() => false)) {
        levels.push(cached);
        continue;
      }
      if (size === meta.width) {
        await copyFile(source, output);
      } else {
        // Sample the original once. Mitchell gently prefilters fine terrain;
        // no sharpening, chained thumbnails, palette quantization or alpha loss.
        await sharp(bytes).resize(size, size, { kernel: "mitchell", withoutEnlargement: true })
          .png({ compressionLevel: 9, palette: false }).toFile(output);
      }
      const derived = await readFile(output);
      const sha256 = hash(derived);
      levels.push({ size, file, bytes: derived.length, sha256,
        url: `/art/derived/planets/${PLANET_ART_VERSION}/${file}?v=${sha256.slice(0, 12)}` });
      written++;
    }
    manifest.planets.push({ slug, source: `art-src/planets-${PLANET_ART_VERSION}/${slug}.png`,
      sourceSha256, ...measured, levels });
  }
  await writeChanged(manifestFile, JSON.stringify(manifest, null, 2) + "\n");
  const catalog = Object.fromEntries(manifest.planets.map(planet => [planet.slug, {
    anchor: planet.anchor, visualRatio: planet.visualRatio,
    levels: planet.levels.map(({ size, url }) => ({ size, url })),
  }]));
  await writeChanged(path.join(clientRoot, "src", "planet-art.generated.ts"),
    "// Generated by scripts/build-planet-derivatives.mjs. Edit the native masters, not this catalog.\n" +
    `export const PLANET_ART = ${JSON.stringify(catalog, null, 2)} as const;\n`);
  return { sources: manifest.planets.length, variants: manifest.planets.length * PLANET_ART_SIZES.length, written };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  console.log("planet derivatives:", await buildPlanetDerivatives());
}
